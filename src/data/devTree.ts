function add(id: string, label: string, url: string, prod: string, parent: string | null, kind: NodeKind = "doc"): AtlasNode {
  const n: AtlasNode = { id, label, url, prod, kind, parent, level: parent ? byId[parent].level + 1 : 0 };
  if (parent) links.push({ source: parent, target: id, kind });
  nodes.push(n); byId[id] = n; return n;
}
const slug = (path: string) => path.replace(/^https?:\/\/[^/]+/, "").replace(/\/main\/?$/, "").replace(/^\/(docs\/)?/, "").replace(/[^a-z0-9]+/gi, "-").replace(/^-|-$/g, "").toLowerCase();

/** Adds rows under a hub; depth 0 rows hang off the hub, deeper rows off the previous shallower row. */
function section(hub: string, prod: string, list: Row[], kind: NodeKind = "doc", pinTop = false) {
  const stack: AtlasNode[] = [];
  let group = prod;
  list.forEach(([depth, label, path, g]) => {
    if (depth === 0 && g) group = g;
    const parent = depth === 0 ? hub : stack[depth - 1].id;
    let id = "d-" + slug(path);
    while (byId[id]) id += "-x"; // the same page can sit under two topics
    const n = add(id, label, path.startsWith("http") ? path : DEV + path, group, parent, kind);
    if (pinTop && depth === 0) n.pin = true;
    stack[depth] = n; stack.length = depth + 1;
  });
}

